import { MENU_TYPES } from "@/lib/pricing";
import {
  SITE_URL_BASE,
  PHONE_E164,
  PHONE_PRETTY,
  EMAIL,
  FOUNDED_YEAR,
  EVENTS_DONE,
  GUESTS_SERVED,
  SOCIALS,
} from "@/lib/site-config";

/** «2 450» / «120 000» — русская группировка разрядов. */
function fmt(n: number): string {
  return new Intl.NumberFormat("ru-RU").format(n);
}

/** Русская плюрализация: 1 гость / 22 гостя / 15 гостей. */
function pluralRu(n: number, forms: readonly [string, string, string]): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return forms[0];
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return forms[1];
  return forms[2];
}

/** Единица минимального заказа: люди по умолчанию, наборы/порции — для доставки. */
const MIN_UNITS: Record<string, readonly [string, string, string]> = {
  "snack-box": ["набор", "набора", "наборов"],
  "office-lunch": ["порция", "порции", "порций"],
};
const GUEST_FORMS: readonly [string, string, string] = ["гость", "гостя", "гостей"];

export function GET(): Response {
  const prices = MENU_TYPES.map((m) => {
    const forms = MIN_UNITS[m.id] ?? GUEST_FORMS;
    const unit = pluralRu(m.minGuests, forms);
    return `${m.label.toLowerCase()} — от ${fmt(m.perGuest)} ₽/чел (минимум ${m.minGuests} ${unit})`;
  }).join("; ");

  const body = [
    `# nilov catering`,
    ``,
    `> Премиальный кейтеринг полного цикла в Санкт-Петербурге. С ${FOUNDED_YEAR} года — ${fmt(EVENTS_DONE)}+ мероприятий и ${fmt(GUESTS_SERVED)}+ гостей: фуршеты, банкеты, свадьбы, корпоративы, кофе-брейки, выездное барбекю, обеды в офис и доставка закусок. «Еда как искусство» — выездной ресторан с поварами и официантами на вашей площадке.`,
    ``,
    `Ключевые факты: работаем с ${FOUNDED_YEAR} года (${fmt(EVENTS_DONE)}+ мероприятий, ${fmt(GUESTS_SERVED)}+ гостей); основатель — Дмитрий Нилов, ИП Нилов Дмитрий Игоревич; телефон ${PHONE_PRETTY} (tel:${PHONE_E164}), Telegram и WhatsApp — на этот же номер; email ${EMAIL}; офис — Санкт-Петербург, ул. Полевая-Сабировская, 45к1; заявки принимаем круглосуточно. Оплата: предоплата 30% при подтверждении заказа, окончательный расчёт — не позднее 3 дней до мероприятия (условия публичной оферты); срочные заказы за 24 часа — возможны с наценкой 25%; вегетарианное, веганское, безглютеновое, халяль, кошер — без доплат.`,
    ``,
    `Форматы и цены «от» (те же данные, что в калькуляторе на главной): ${prices}. В высокий сезон (май–сентябрь, декабрь) смета умножается на коэффициент ×1,15. В стоимость входит: еда, доставка в пределах КАД, сервировка, посуда и текстиль, повар и официанты на месте, лёгкое цветочное сопровождение. Не входит: аренда площадки, алкоголь, музыка, расширенная флористика — поможем организовать по запросу. Приватная дегустация в студии — ${fmt(3500)} ₽/чел (шесть блюд из будущего меню, сумма возвращается при заказе от 50 гостей).`,
    ``,
    `## Основное`,
    ``,
    `- [nilov catering — главная](${SITE_URL_BASE}/): портфолио, видео мероприятий, меню и интерактивный калькулятор стоимости — смета-чек за 30 секунд.`,
    `- [Калькулятор стоимости](${SITE_URL_BASE}/#calculator): расчёт сметы по формату события, числу гостей и дате с учётом сезонного коэффициента; заявка отправляется прямо из калькулятора.`,
    `- [Меню и форматы](${SITE_URL_BASE}/#menu): пакеты «Базовый» / «Стандарт» / «Премиум» по каждому формату — состав позиций и граммовки каждой подачи.`,
    `- [Частые вопросы](${SITE_URL_BASE}/#faq): минимальные заказы, сроки бронирования, что входит в стоимость, диеты и аллергии, оплата, дегустация.`,
    ``,
    `## Документы`,
    ``,
    `- [Публичная оферта](${SITE_URL_BASE}/offer): условия оказания кейтеринговых услуг — перечень услуг, стоимость и порядок расчётов (предоплата 30%), сроки, расторжение договора, реквизиты ИП.`,
    `- [Политика конфиденциальности](${SITE_URL_BASE}/privacy): порядок обработки персональных данных в соответствии с 152-ФЗ.`,
    `- [Пользовательское соглашение](${SITE_URL_BASE}/terms): правила использования сайта и порядок заключения договора на кейтеринговые услуги.`,
    ``,
    `## Optional`,
    ``,
    `- [Instagram](${SOCIALS.instagram}): фотоотчёты с мероприятий и Reels.`,
    `- [ВКонтакте](${SOCIALS.vk}): сообщество компании, новости и кейсы.`,
    `- [Telegram](${SOCIALS.telegram}): прямая переписка с менеджером (номер ${PHONE_PRETTY}).`,
    `- [WhatsApp](${SOCIALS.whatsapp}): быстрый расчёт и бронирование (номер ${PHONE_PRETTY}).`,
    `- [MAX](${SOCIALS.max}): официальный аккаунт в российском мессенджере MAX.`,
    ``,
  ].join("\n");

  return new Response(body, {
    headers: {
      "Content-Type": "text/markdown; charset=utf-8",
      "Cache-Control": "public, max-age=3600, s-maxage=86400",
    },
  });
}
